# what is arrange() fucntion in numpy
# arrange funtion is used to create a one-D numpy array having sequence of number
# syntax np.arrange(starting value,stop,step)

import numpy as np

# sequence 1:
num_py1=np.arange(1,10,1)
print(num_py1)

# sequence 2:
num_py2=np.arange(1,10,2)
print(num_py2)

#sequence 3:
num_py3=np.arange(1,10,3)
print(num_py3)



